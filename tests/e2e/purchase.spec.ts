test('cliques repetidos e reenvio idempotente não duplicam; conteúdo diferente conflita', async ({ page }) => {
  await open(page, 'pending')
  await checkout(page)
  await page.getByRole('button', { name: 'Confirmar compra fictícia' }).evaluate(button => { (button as HTMLButtonElement).click(); (button as HTMLButtonElement).click() })
  await expect(page.getByRole('heading', { name: 'Pedido pendente' })).toBeVisible()
  const orders = (await api(page, '/orders')).data
  expect(orders).toHaveLength(1)
  const order = orders[0]
  const repeated = await Promise.all([api(page, '/orders', 'POST', order.input, { 'Idempotency-Key': order.key }), api(page, '/orders', 'POST', order.input, { 'Idempotency-Key': order.key })])
  for (const response of repeated) { expect(response.status).toBe(200); expect(response.data.id).toBe(order.id) }
  const conflict = await api(page, '/orders', 'POST', { ...order.input, buyer: { ...order.input.buyer, name: 'Outro nome' } }, { 'Idempotency-Key': order.key })
  expect(conflict.status).toBe(409)
  expect(conflict.data.code).toBe('IDEMPOTENCY_CONFLICT')
  expect((await api(page, '/orders')).data).toHaveLength(1)
})

