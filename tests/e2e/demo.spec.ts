import { expect, test, type Page } from '@playwright/test'

async function read(page: Page) {
  return page.evaluate(async () => (await fetch('/api/demo')).json())
}
async function configure(page: Page, catalog: string, loginDelayMs: number) {
  await page.getByLabel('Rede do catálogo').selectOption(catalog)
  await page.getByLabel('Latência do login (ms)').fill(String(loginDelayMs))
  const applied = page.waitForResponse(r => r.url().endsWith('/api/demo') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Aplicar condições' }).click()
  expect((await applied).fromServiceWorker()).toBe(true)
  await expect(page.getByRole('status').filter({ hasText: 'Comando executado' })).toBeVisible()
}

test('Cenários consulta e restaura seleções efetivas após navegação e refresh', async ({ page }) => {
  const loaded = page.waitForResponse(r => r.url().endsWith('/api/demo') && r.request().method() === 'GET')
  await page.goto('/demo')
  expect((await loaded).fromServiceWorker()).toBe(true)
  await configure(page, 'http-error', 650)
  expect((await read(page)).networkConditions).toEqual({ catalog: 'http-error', loginDelayMs: 650 })
  await page.getByRole('link', { name: 'Início', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('temporariamente indisponível')
  await expect(page.getByText('Uma falha de rede está forçada', { exact: false })).toBeVisible()
  const retried = page.waitForResponse(r => new URL(r.url()).pathname === '/api/nfts')
  await page.getByRole('button', { name: 'Tentar novamente' }).click()
  expect((await retried).status()).toBe(503)
  await expect(page.getByRole('alert')).toContainText('temporariamente indisponível')
  await page.getByRole('link', { name: 'Abrir Cenários', exact: true }).click()
  await expect(page.getByLabel('Rede do catálogo')).toHaveValue('http-error')
  await expect(page.getByLabel('Latência do login (ms)')).toHaveValue('650')
  await page.reload()
  await expect(page.getByLabel('Rede do catálogo')).toHaveValue('http-error')
  await expect(page.getByLabel('Latência do login (ms)')).toHaveValue('650')
  await configure(page, 'normal', 200)
  await page.getByRole('link', { name: 'Início', exact: true }).click()
  await expect(page.getByTestId('nft-grid').getByRole('article')).toHaveCount(9)
  await page.getByRole('link', { name: 'Cenários da demonstração', exact: true }).click()
  await expect(page.getByLabel('Rede do catálogo')).toHaveValue('normal')
  await expect(page.getByLabel('Latência do login (ms)')).toHaveValue('200')
})

test('reset restaura condições, latência e catálogo e apresenta o cenário efetivo', async ({ page }) => {
  await page.goto('/demo')
  await configure(page, 'slow', 1200)
  await page.getByLabel('Cenário', { exact: true }).selectOption('pending')
  await page.getByRole('button', { name: 'Restaurar cenário', exact: true }).click()
  await expect(page.getByTestId('nft-grid').getByRole('article')).toHaveCount(9)
  expect(await read(page)).toEqual({ scenario: 'pending', networkConditions: { catalog: 'normal', loginDelayMs: 0 } })
  await page.getByRole('link', { name: 'Cenários da demonstração', exact: true }).click()
  await expect(page.getByLabel('Cenário', { exact: true })).toHaveValue('pending')
  await expect(page.getByLabel('Rede do catálogo')).toHaveValue('normal')
  await expect(page.getByLabel('Latência do login (ms)')).toHaveValue('0')
  await page.reload()
  await expect(page.getByLabel('Cenário', { exact: true })).toHaveValue('pending')
})

for (const catalog of ['http-error', 'network-error']) test(`restaurar rede no catálogo recupera ${catalog} sem perder URL`, async ({ page }) => {
  await page.goto('/demo')
  await configure(page, catalog, 900)
  await page.goto('/?q=Emerald&sort=price-asc')
  await expect(page.getByRole('alert')).toBeVisible()
  await page.getByRole('button', { name: 'Restaurar rede normal', exact: true }).click()
  await expect(page.getByTestId('nft-grid').getByRole('article')).toHaveCount(4)
  await expect(page.getByRole('searchbox', { name: 'Buscar NFTs' })).toHaveValue('Emerald')
  await expect(page.getByLabel('Ordenar NFTs')).toHaveValue('price-asc')
  expect((await read(page)).networkConditions).toEqual({ catalog: 'normal', loginDelayMs: 0 })
  await page.reload()
  await expect(page.getByTestId('nft-grid').getByRole('article')).toHaveCount(4)
})
